  task_id VARCHAR(100) COLLATE utf8mb4_0900_bin NOT NULL,
  agent_id VARCHAR(100) COLLATE utf8mb4_0900_bin NOT NULL,
  principal_type VARCHAR(20) COLLATE utf8mb4_0900_bin NOT NULL,
  principal_id VARCHAR(100) COLLATE utf8mb4_0900_bin NOT NULL,
  idempotency_key VARBINARY(36) NOT NULL,
  request_hash BINARY(32) NOT NULL,
  task_version BIGINT NOT NULL,
  price_book_version VARCHAR(100) COLLATE utf8mb4_0900_bin NOT NULL,
  task_input_hash VARCHAR(71) COLLATE utf8mb4_0900_bin NOT NULL,
  skill_set_hash VARCHAR(71) COLLATE utf8mb4_0900_bin NOT NULL,
  model_route_version VARCHAR(100) COLLATE utf8mb4_0900_bin NOT NULL,
  estimated_input_tokens BIGINT NOT NULL,
  estimated_cached_input_tokens BIGINT NOT NULL,
  estimated_output_tokens BIGINT NOT NULL,
  estimated_reasoning_tokens BIGINT NOT NULL,
  estimated_compute_wen BIGINT NOT NULL,
  worst_compute_wen BIGINT NOT NULL,
  platform_fee_wen BIGINT NOT NULL,
  gross_allocation_wen BIGINT NOT NULL,
  estimated_agent_payout_wen BIGINT NOT NULL,
  worst_agent_payout_wen BIGINT NOT NULL,
  minimum_accepted_payout_wen BIGINT NOT NULL,
  budget_headroom_wen BIGINT NOT NULL,
  verified_skill_match TINYINT(1) NOT NULL,
  advisory_ability_match TINYINT(1) NOT NULL,
  budget_covered TINYINT(1) NOT NULL,
  agent_ready TINYINT(1) NOT NULL,
  recommendation VARCHAR(20) COLLATE utf8mb4_0900_bin NOT NULL,
  reason_codes TEXT COLLATE utf8mb4_0900_bin NOT NULL,
  status VARCHAR(16) COLLATE utf8mb4_0900_bin NOT NULL DEFAULT 'OPEN',
  expires_at BIGINT NOT NULL,
  claimed_at BIGINT NULL,
  tenant_id VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL,
  client_id VARCHAR(50) COLLATE utf8mb4_0900_bin NOT NULL,
